"""Regenerates src/UpSTEPer.App/Themes/Icons.axaml from Lucide SVG icons (ISC licence).

Usage: python scripts/update-icons.py <folder with the SVG files of ICONS>
Download the SVGs from https://unpkg.com/lucide-static@<VERSION>/icons/<name>.svg first; the
app never loads icons at run time. Each icon becomes a StreamGeometry "Icon.<PascalName>" on the
24x24 Lucide grid, drawn as a stroke by the Icon control.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

VERSION = "1.56.0"
ICONS = [
    "axis-3d", "box", "boxes", "check", "chevron-down", "circle-check", "circle-x", "ellipsis",
    "eraser", "eye", "file-output", "folder-open", "frame", "gauge", "info", "keyboard",
    "list-tree", "loader-circle", "paint-bucket", "paintbrush", "palette", "panel-left", "pipette",
    "plus", "redo-2", "rotate-3d", "save", "scan", "scan-search", "square", "triangle",
    "triangle-alert", "undo-2", "wrench", "x",
]
OUTPUT = os.path.join(os.path.dirname(__file__), "..", "src", "UpSTEPer.App", "Themes", "Icons.axaml")


def num(x):
    s = ("%.3f" % x).rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def rect(a):
    x, y, w, h = (float(a.get(k, 0)) for k in ("x", "y", "width", "height"))
    rx = float(a.get("rx", a.get("ry", 0)))
    ry = float(a.get("ry", rx))
    if rx == 0:
        return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
    arc = f"A{num(rx)} {num(ry)} 0 0 1"
    return (f"M{num(x + rx)} {num(y)}H{num(x + w - rx)}{arc} {num(x + w)} {num(y + ry)}"
            f"V{num(y + h - ry)}{arc} {num(x + w - rx)} {num(y + h)}H{num(x + rx)}"
            f"{arc} {num(x)} {num(y + h - ry)}V{num(y + ry)}{arc} {num(x + rx)} {num(y)}Z")


def circle(a):
    cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
    arc = f"A{num(r)} {num(r)} 0 1 0"
    return f"M{num(cx - r)} {num(cy)}{arc} {num(cx + r)} {num(cy)}{arc} {num(cx - r)} {num(cy)}Z"


def points(a, close):
    p = re.split(r"[\s,]+", a["points"].strip())
    return "M" + "L".join(f"{x} {y}" for x, y in zip(p[0::2], p[1::2])) + ("Z" if close else "")


def path(a):
    # A path's first "m" is absolute, but the coordinate pairs after it are relative line-tos.
    # The paths are concatenated, so write the start as "M x y" and the rest as an explicit "l".
    d = a["d"].strip()
    match = re.match(r"m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)\s*,?\s*(.*)", d, re.S)
    if not match:
        return d
    x, y, rest = match.groups()
    if rest and not rest[0].isalpha():
        rest = "l" + rest
    return f"M{x} {y}{rest}"


CONVERTERS = {
    "path": path,
    "rect": rect,
    "circle": circle,
    "line": lambda a: f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}",
    "polyline": lambda a: points(a, False),
    "polygon": lambda a: points(a, True),
}


def main(folder):
    lines = []
    for name in ICONS:
        root = ET.parse(os.path.join(folder, name + ".svg")).getroot()
        parts = [CONVERTERS[element.tag.split("}")[-1]](element.attrib) for element in root]
        key = "Icon." + "".join(word.capitalize() for word in name.split("-"))
        lines.append(f'  <StreamGeometry x:Key="{key}">{" ".join(parts)}</StreamGeometry>')

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as output:
        output.write(f"<!-- Generated by scripts/update-icons.py from Lucide {VERSION} (ISC licence, Lucide-LICENSE.txt).\n"
                     "     Stroke icons on a 24x24 grid, drawn by the Icon control. Do not edit by hand. -->\n")
        output.write('<ResourceDictionary xmlns="https://github.com/avaloniaui"\n'
                     '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n')
        output.write("\n".join(lines) + "\n</ResourceDictionary>\n")
    print(f"{len(lines)} icons written to {os.path.normpath(OUTPUT)}")


if __name__ == "__main__":
    main(sys.argv[1])
