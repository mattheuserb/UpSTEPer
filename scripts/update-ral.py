"""Regenerates src/UpSTEPer.App/Colours/ral-classic.json from Wikidata (CC0, public domain).

Usage: python scripts/update-ral.py

RAL publishes no official sRGB values; every list is an approximation. Wikidata items of class
"RAL colour" (Q17421658) carry the hex value (P465) and the German / English names in their
descriptions ("RAL Farbe Steingrau", "RAL color stone grey"). Rules:
- Several hex values: the first one with a reference URL (P854), else the first in statement order.
- Missing or broken names are completed from NAMES below (official RAL names; names are facts).
- Colours without a hex value in Wikidata are left out and listed in the output.
"""
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from datetime import date

OUTPUT = os.path.join(os.path.dirname(__file__), "..", "src", "UpSTEPer.App", "Colours", "ral-classic.json")
USER_AGENT = "UpSTEPer/0.1 (https://github.com/mattheuserb/UpSTEPer)"
QUERY = """
SELECT ?item ?label ?descEn ?descDe WHERE {
  ?item wdt:P31 wd:Q17421658 .
  ?item rdfs:label ?label FILTER(LANG(?label) = "en")
  OPTIONAL { ?item schema:description ?descEn FILTER(LANG(?descEn) = "en") }
  OPTIONAL { ?item schema:description ?descDe FILTER(LANG(?descDe) = "de") }
}"""

# Items whose label is not "RAL nnnn".
CODES = {"Q2516404": "3020"}

# Official RAL names where Wikidata's descriptions lack them: code -> (German, English).
NAMES = {
    "2002": ("Blutorange", "Vermilion"),
    "3003": ("Rubinrot", "Ruby red"),
    "3020": ("Verkehrsrot", "Traffic red"),
}


def fetch_json(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.load(response)


def hex_value(item):
    """The hex value by the rules above, or None."""
    claims = fetch_json(f"https://www.wikidata.org/wiki/Special:EntityData/{item}.json")["entities"][item]["claims"].get("P465", [])
    values = [(c["mainsnak"]["datavalue"]["value"], any("P854" in r["snaks"] for r in c.get("references", [])))
              for c in claims if c["rank"] != "deprecated" and "datavalue" in c["mainsnak"]]
    for value, referenced in values:
        if referenced:
            return value
    return values[0][0] if values else None


def name(description, prefix):
    if description and description.startswith(prefix):
        rest = description[len(prefix):].strip()
        return rest[:1].upper() + rest[1:] if rest else None
    return None


def main():
    url = "https://query.wikidata.org/sparql?" + urllib.parse.urlencode({"query": QUERY, "format": "json"})
    rows = fetch_json(url)["results"]["bindings"]
    colours, skipped = {}, []
    for row in rows:
        item = row["item"]["value"].rsplit("/", 1)[1]
        label = row["label"]["value"]
        match = re.fullmatch(r"RAL (\d{4})", label)
        code = match.group(1) if match else CODES.get(item)
        if code is None or code in colours:
            continue
        german = name(row.get("descDe", {}).get("value"), "RAL Farbe")
        english = name(row.get("descEn", {}).get("value"), "RAL color")
        if code in NAMES:
            german, english = NAMES[code]
        value = hex_value(item)
        if value is None or not german or not english:
            skipped.append(code)
            continue
        colours[code] = {"code": code, "de": german, "en": english, "hex": "#" + value.upper()}

    document = {
        "source": "Wikidata (CC0), items of class RAL colour (Q17421658); generated by scripts/update-ral.py",
        "retrieved": date.today().isoformat(),
        "note": "Approximate sRGB values; RAL publishes no official ones. RAL is a registered trademark of RAL gGmbH.",
        "colours": [colours[code] for code in sorted(colours)],
    }
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as output:
        json.dump(document, output, ensure_ascii=False, indent=1)
        output.write("\n")
    print(f"{len(colours)} colours written to {os.path.normpath(OUTPUT)}; left out (no hex value or name): {sorted(skipped)}")


if __name__ == "__main__":
    sys.exit(main())
